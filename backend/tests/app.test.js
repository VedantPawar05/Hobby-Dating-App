import { describe, it, expect } from 'vitest';
import request from 'supertest';
import app from '../src/app.js';

describe('Express Application & Core Endpoints', () => {
  it('GET /api/health returns 200 with structured health data', async () => {
    const res = await request(app).get('/api/health');

    expect(res.status).toBe(200);
    expect(res.body).toHaveProperty('success', true);
    expect(res.body).toHaveProperty('message', 'API is running');
    expect(res.body).toHaveProperty('data');
    expect(res.body.data).toMatchObject({
      status: 'healthy',
      environment: expect.any(String),
      database: expect.any(String),
    });
    expect(new Date(res.body.data.timestamp).toISOString()).toBe(res.body.data.timestamp);
  });

  it('Unknown route returns 404 with standardized error response', async () => {
    const res = await request(app).get('/api/non-existent-endpoint');

    expect(res.status).toBe(404);
    expect(res.body).toEqual({
      success: false,
      message: 'Cannot GET /api/non-existent-endpoint',
    });
  });

  it('Unknown POST route returns 404', async () => {
    const res = await request(app).post('/unmapped-url').send({ key: 'val' });

    expect(res.status).toBe(404);
    expect(res.body).toEqual({
      success: false,
      message: 'Cannot POST /unmapped-url',
    });
  });

  it('Invalid JSON payload is caught and returns 400 Bad Request', async () => {
    const res = await request(app)
      .post('/api/health')
      .set('Content-Type', 'application/json')
      .send('{ "broken_json": ');

    expect(res.status).toBe(400);
    expect(res.body).toHaveProperty('success', false);
    expect(res.body).toHaveProperty('message', 'Invalid JSON payload received');
  });

  it('Includes security headers generated by Helmet', async () => {
    const res = await request(app).get('/api/health');

    expect(res.headers).toHaveProperty('x-content-type-options', 'nosniff');
    expect(res.headers).toHaveProperty('x-dns-prefetch-control', 'off');
  });
});

