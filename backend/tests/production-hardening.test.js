describe('Phase 8 — Production Readiness & Deployment Hardening', () => {
  beforeEach(() => {
    vi.restoreAllMocks();
  });

  describe('Health & Observability Probes', () => {
    it('GET /api/health returns 200 with runtime and database status', async () => {
      const res = await request(app).get('/api/health');

      expect(res.status).toBe(200);
      expect(res.body.success).toBe(true);
      expect(res.body.data).toMatchObject({
        status: 'healthy',
        environment: expect.any(String),
        database: expect.any(String),
        uptime: expect.any(Number),
      });
    });

    it('GET /api/health/live returns 200 for container liveness check', async () => {
      const res = await request(app).get('/api/health/live');

      expect(res.status).toBe(200);
      expect(res.body.success).toBe(true);
      expect(res.body.data).status = 'live';
      expect(typeof res.body.data.uptime).toBe('number');
    });

    it('GET /api/health/ready returns 200 when database is connected', async () => {
      vi.spyOn(databaseModule, 'getDatabaseStatus').mockReturnValue('connected');

      const res = await request(app).get('/api/health/ready');

      expect(res.status).toBe(200);
      expect(res.body.success).toBe(true);
      expect(res.body.data.status).toBe('ready');
      expect(res.body.data.database).toBe('connected');
    });

    it('GET /api/health/ready returns 503 Service Unavailable when database is disconnected', async () => {
      vi.spyOn(databaseModule, 'getDatabaseStatus').mockReturnValue('disconnected');

      const res = await request(app).get('/api/health/ready');

      expect(res.status).toBe(503);
      expect(res.body.success).toBe(false);
      expect(res.body.message).toMatch(/database connection not ready/i);
    });

    it('GET /api/health/ready handles exceptions gracefully and returns 503', async () => {
      vi.spyOn(databaseModule, 'getDatabaseStatus').mockImplementation(() => {
        throw new Error('Connection poll failure');
      });

      const res = await request(app).get('/api/health/ready');

      expect(res.status).toBe(503);
      expect(res.body.success).toBe(false);
      expect(res.body.message).toMatch(/database connection not ready/i);
    });
  });

  describe('Security Headers & CORS Protection', () => {
    it('serves hardened security headers generated by Helmet', async () => {
      const res = await request(app).get('/api/health');

      expect(res.headers).toHaveProperty('x-content-type-options', 'nosniff');
      expect(res.headers).toHaveProperty('x-dns-prefetch-control', 'off');
    });

    it('rejects cross-origin requests from untrusted origins with 403 Forbidden', async () => {
      const res = await request(app)
        .get('/api/health')
        .set('Origin', 'https://malicious-phishing-site.example');

      expect(res.status).toBe(403);
      expect(res.body.message).toMatch(/not allowed by CORS/i);
    });

    it('allows requests from valid configured CLIENT_URL origins', async () => {
      const res = await request(app)
        .get('/api/health')
        .set('Origin', 'http://localhost:3000');

      expect(res.status).toBe(200);
      expect(res.headers['access-control-allow-origin']).toBe('http://localhost:3000');
    });
  });

  describe('NoSQL Injection & Payload Sanitization Hardening', () => {
    it('recursively strips keys starting with $ or containing . from input objects', () => {
      const maliciousPayload = {
        email: 'user@example.com',
        password: 'securePassword123!',
        $gt: '',
        nested: {
          validField: 123,
          $where: 'function() { return true; }',
          'dotted.key': 'exploit',
        },
        items: [
          { name: 'Item 1', $ne: null },
          'plain-string',
        ],
      };

      const sanitized = sanitizeNoSqlInput(maliciousPayload);

      expect(sanitized.email).toBe('user@example.com');
      expect(sanitized.password).toBe('securePassword123!');
      expect(sanitized.$gt).toBeUndefined();
      expect(sanitized.nested.validField).toBe(123);
      expect(sanitized.nested.$where).toBeUndefined();
      expect(sanitized.nested['dotted.key']).toBeUndefined();
      expect(sanitized.items[0].$ne).toBeUndefined();
      expect(sanitized.items[0].name).toBe('Item 1');
      expect(sanitized.items[1]).toBe('plain-string');
    });

    it('rejects payloads exceeding the recursion depth limit of 8 with an error', () => {
      let deeplyNested = { value: 'leaf' };
      for (let i = 0; i < 9; i++) {
        deeplyNested = { child: deeplyNested };
      }

      expect(() => sanitizeNoSqlInput(deeplyNested)).toThrow(
        /nesting depth exceeds/i
      );
    });

    it('rejects prototype pollution injection keys (__proto__, constructor, prototype) with an error', () => {
      const protoPayload = JSON.parse('{"__proto__": {"isAdmin": true}}');
      expect(() => sanitizeNoSqlInput(protoPayload)).toThrow(
        /prototype pollution/i
      );

      const constructorPollution = {
        constructor: { prototype: { hacked: true } },
      };
      expect(() => sanitizeNoSqlInput(constructorPollution)).toThrow(
        /prototype pollution/i
      );
    });

    it('preserves Date, Buffer, and RegExp instances intact without mutation', () => {
      const now = new Date();
      const buf = Buffer.from('binary-safe');
      const reg = /^test/i;

      const input = {
        createdAt: now,
        data: buf,
        pattern: reg,
      };

      const sanitized = sanitizeNoSqlInput(input);
      expect(sanitized.createdAt).toBe(now);
      expect(sanitized.data).toBe(buf);
      expect(sanitized.pattern).toBe(reg);
    });

    it('returns HTTP 400 when an incoming HTTP payload violates prototype-pollution constraints', async () => {
      const res = await request(app)
        .post('/api/auth/login')
        .set('Content-Type', 'application/json')
        .send('{"email":"valid@example.com","password":"password123","__proto__":{"injected":true}}');

      expect(res.status).toBe(400);
      expect(res.body.success).toBe(false);
      expect(res.body.message).toMatch(/prototype pollution/i);
    });
  });

  describe('User Account Deletion, Deactivation & Referential Consistency', () => {
    it('cancels active bookings upon account deletion and rejects repeat deletion', async () => {
      const mockUserId = new mongoose.Types.ObjectId().toString();
      const mockUser = {
        _id: mockUserId,
        email: 'delete-me@example.com',
        isActive: true,
        deletedAt: null,
        comparePassword: vi.fn().mockResolvedValue(true),
        save: vi.fn().mockResolvedValue(true),
      };

      vi.spyOn(User, 'findById').mockReturnValue({
        select: vi.fn().mockResolvedValue(mockUser),
      });
      vi.spyOn(Booking, 'updateMany').mockResolvedValue({ modifiedCount: 2 });

      // First deletion: succeeds
      const result = await UserService.deleteAccount(mockUserId, 'securePass123!', 'DELETE');
      expect(result.deleted).toBe(true);
      expect(mockUser.isActive).toBe(false);
      expect(mockUser.deletedAt).toBeInstanceOf(Date);
      expect(Booking.updateMany).toHaveBeenCalledWith(
        { user: mockUser._id, status: BOOKING_STATUSES.CONFIRMED },
        { $set: { status: BOOKING_STATUSES.CANCELLED, cancelledAt: expect.any(Date) } }
      );

      // Second deletion attempt on already deleted account: rejected with HTTP 400
      await expect(
        UserService.deleteAccount(mockUserId, 'securePass123!', 'DELETE')
      ).rejects.toThrow(/already been permanently deleted/i);
    });

    it('rejects sending chat messages to an inactive or deleted recipient with HTTP 403', async () => {
      const senderId = new mongoose.Types.ObjectId().toString();
      const deletedRecipientId = new mongoose.Types.ObjectId().toString();
      const conversationId = new mongoose.Types.ObjectId().toString();

      vi.spyOn(Conversation, 'findById').mockResolvedValue({
        _id: conversationId,
        match: new mongoose.Types.ObjectId(),
        participants: [senderId, deletedRecipientId],
        isActive: true,
      });

      vi.spyOn(BlockService, 'isBlocked').mockResolvedValue(false);

      // Recipient is marked deleted / inactive
      vi.spyOn(User, 'findById').mockResolvedValue({
        _id: deletedRecipientId,
        isActive: false,
        deletedAt: new Date(),
      });

      await expect(
        ChatService.sendMessage(conversationId, senderId, 'Hello to deleted user')
      ).rejects.toThrow(/recipient account is inactive or deleted/i);
    });
  });

  describe('Structured Logger Sanitization & Sensitive Data Redaction', () => {
    it('redacts passwords, tokens, secrets, cookies, and chat contents', () => {
      const input = {
        username: 'alice',
        password: 'SuperSecretPassword123!',
        currentPassword: 'OldPassword456',
        secretKey: 'top_secret_value',
        authorization: 'Bearer token_value',
        cookie: 'access_token=xyz',
        content: 'Hey, this is a private personal chat message',
        otherInfo: 'normal data',
      };

      const sanitized = sanitizeLogData(input);

      expect(sanitized.username).toBe('alice');
      expect(sanitized.password).toBe('[REDACTED]');
      expect(sanitized.currentPassword).toBe('[REDACTED]');
      expect(sanitized.secretKey).toBe('[REDACTED]');
      expect(sanitized.authorization).toBe('[REDACTED]');
      expect(sanitized.cookie).toBe('[REDACTED]');
      expect(sanitized.content).toBe('[REDACTED]');
      expect(sanitized.otherInfo).toBe('normal data');
    });

    it('redacts standalone and embedded JWT tokens with Bearer prefixes', () => {
      const standaloneJwt =
        'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0NTY3ODkwIiwibmFtZSI6IkpvaG4ifQ.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJV_adQssw5c';

      expect(sanitizeLogData(standaloneJwt)).toBe('[REDACTED_JWT]');

      const embeddedBearer = `Bearer ${standaloneJwt}`;
      expect(sanitizeLogData(embeddedBearer)).toBe('[REDACTED_JWT]');
    });

    it('masks Error objects and suppresses stack trace in production', () => {
      const err = new Error('Database connection failed with password=SecretKey123');
      err.stack = 'Error at /app/src/db.js:10:15';

      const originalEnv = env.NODE_ENV;
      try {
        env.NODE_ENV = 'production';
        const sanitizedErr = sanitizeLogData(err);
        expect(sanitizedErr.name).toBe('Error');
        expect(sanitizedErr.message).toBe('Database connection failed with password=[REDACTED]');
        expect(sanitizedErr.stack).toBeUndefined();
      } finally {
        env.NODE_ENV = originalEnv;
      }
    });
  });

  describe('Socket Disconnect Cleanup & Room Authorization', () => {
    it('emits USER_STOP_TYPING to all active conversation rooms when a socket disconnects', () => {
      let registeredListeners = {};
      const mockSocket = {
        id: 'socket_123',
        userId: 'user_456',
        activeConversationRooms: new Set(['room_alpha', 'room_beta']),
        to: vi.fn().mockReturnValue({
          emit: vi.fn(),
        }),
        on: vi.fn((event, cb) => {
          registeredListeners[event] = cb;
        }),
      };

      registerSocketEvents(mockSocket, 'user_456');

      // Trigger disconnect
      expect(registeredListeners['disconnect']).toBeDefined();
      registeredListeners['disconnect']();

      // Should emit USER_STOP_TYPING to both active rooms
      expect(mockSocket.to).toHaveBeenCalledWith('conversation:room_alpha');
      expect(mockSocket.to).toHaveBeenCalledWith('conversation:room_beta');
    });
  });

  describe('Rate Limiter Behavior & Headers', () => {
    it('enforces limit and sets X-RateLimit headers when enabled in test', async () => {
      const testLimiter = createRateLimiter({
        windowMs: 60 * 1000,
        max: 2,
        message: 'Rate limit test exceeded',
        enabledInTest: true,
        keyGenerator: () => 'test_isolated_key',
      });

      const mockReq = { ip: '127.0.0.1', baseUrl: '/test' };
      const headers = {};
      const mockRes = {
        setHeader: vi.fn((k, v) => {
          headers[k] = v;
        }),
        status: vi.fn().mockReturnThis(),
        json: vi.fn(),
      };
      const nextFn = vi.fn();

      // Request 1: allowed
      testLimiter(mockReq, mockRes, nextFn);
      expect(nextFn).toHaveBeenCalledTimes(1);
      expect(headers['X-RateLimit-Limit']).toBe('2');
      expect(headers['X-RateLimit-Remaining']).toBe('1');

      // Request 2: allowed
      testLimiter(mockReq, mockRes, nextFn);
      expect(nextFn).toHaveBeenCalledTimes(2);
      expect(headers['X-RateLimit-Remaining']).toBe('0');

      // Request 3: blocked
      testLimiter(mockReq, mockRes, nextFn);
      expect(nextFn).toHaveBeenCalledTimes(2); // Not called again
      expect(mockRes.status).toHaveBeenCalledWith(429);
      expect(headers['Retry-After']).toBeDefined();
    });

    it('account-based rate limiter trips after 10 attempts for the same email regardless of differing IPs', () => {
      const accountLimiter = createRateLimiter({
        windowMs: 15 * 60 * 1000,
        max: 10,
        message: 'Account rate limit reached',
        enabledInTest: true,
        keyGenerator: (req) => {
          const rawEmail = req.body?.email;
          return `auth_account:${rawEmail.toLowerCase().trim()}`;
        },
      });

      const targetEmail = 'victim_user@example.com';
      const mockRes = {
        setHeader: vi.fn(),
        status: vi.fn().mockReturnThis(),
        json: vi.fn(),
      };
      const nextFn = vi.fn();

      // 10 attempts from 10 distinct IP addresses against the same account
      for (let i = 1; i <= 10; i++) {
        accountLimiter(
          { ip: `192.168.1.${i}`, body: { email: targetEmail } },
          mockRes,
          nextFn
        );
      }
      expect(nextFn).toHaveBeenCalledTimes(10);

      // 11th attempt from yet another IP address: should be blocked
      accountLimiter(
        { ip: '192.168.1.99', body: { email: targetEmail } },
        mockRes,
        nextFn
      );
      expect(nextFn).toHaveBeenCalledTimes(10); // Not called again
      expect(mockRes.status).toHaveBeenCalledWith(429);
    });
  });
});
